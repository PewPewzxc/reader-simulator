"""Simulator setup for a CrossPoint-family firmware that has none of its own.
python -I adapter.py <firmware folder> [--newest]
Writes <folder>/platformio.local.ini (which the firmware's platformio.ini already loads through
extra_configs) with the simulator environments from crosspoint-simulator's own sample config,
taken at the library commit from the firmware's time (--newest: today's library). The firmware's
own files are never changed. Environments use the names the launcher knows:
  simulator (X4), x4-classic-simulator, x4-pro-simulator, simulator_x3  - only the models the
  firmware itself builds for. Safe to run again; prints what it did."""
import configparser
import json
import os
import re
import subprocess
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from pin_simlib import github  # noqa: E402  (GITHUB_TOKEN-aware GitHub API call)

LIB = "crosspoint-reader/crosspoint-simulator"
MARK = "; generated by the reader simulator adapter"  # NOT "written by the reader simulator": build.sh retries those
HEAD = MARK + " (adapter.py): simulator environments\n"
# sample section -> (our env name, what the firmware must mention to support that model; None = always)
ENVS = [("simulator", "simulator", None),
        ("simulator_x4_classic", "x4-classic-simulator", "FREEINK_DEVICE_X4CLASSIC"),
        ("simulator_x4_pro", "x4-pro-simulator", "FREEINK_DEVICE_X4PRO"),
        ("simulator_x3", "simulator_x3", r"FREEINK_DEVICE_X3")]  # older ones: one X3+X4 build, deviceIsX3() in src/
# Windows-only additions: AnimatedGIF (in the sample's lib_deps) defines memcpy_P only for Linux-style hosts.
# compat/openssl/sha.h (SHA1/SHA256 for the newer library) is on every build's include path (build.sh);
# RSIM_CROSSPOINT_COMPAT turns on settimeofday/strcasestr in compat/win_sim_prelude.h.
WIN_FLAGS = ["-Dmemcpy_P=memcpy", "-DRSIM_CROSSPOINT_COMPAT"]
SAMPLES = ["sample-platformio-linux-wsl.ini", "sample-platformio.ini"]  # newer name first


def raw(sha, name):
    try:
        with urllib.request.urlopen(f"https://raw.githubusercontent.com/{LIB}/{sha}/{name}", timeout=20) as r:
            return r.read().decode("utf-8")
    except urllib.error.HTTPError:
        return None


def lib_commit(folder, newest):
    if newest:
        return github(f"https://api.github.com/repos/{LIB}/commits?per_page=1")[0]["sha"]
    when = subprocess.run(["git", "-C", folder, "log", "-1", "--format=%cd", "--date=format-local:%Y-%m-%dT%H:%M:%SZ"],
                          capture_output=True, text=True, env=dict(os.environ, TZ="UTC")).stdout.strip()
    if not when:
        return lib_commit(folder, True)
    cache_file = os.path.join(folder, ".rsim-pin.json")  # shared with pin_simlib.py: same format
    try:
        cache = json.load(open(cache_file, encoding="utf-8"))
    except (OSError, ValueError):
        cache = {}
    key = f"{LIB}@{when}"
    if not cache.get(key):
        commits = github(f"https://api.github.com/repos/{LIB}/commits?until={when}&per_page=1")
        if not commits:
            return lib_commit(folder, True)
        cache[key] = commits[0]["sha"]
        json.dump(cache, open(cache_file, "w", encoding="utf-8"))
    return cache[key]


def lines(value):
    return [l.strip() for l in value.splitlines() if l.strip()]


def keep_dep(folder, dep, sha):
    if dep.startswith("simulator=") or LIB in dep:
        return f"simulator=https://github.com/{LIB}#{sha}"
    m = re.search(r"symlink://(\S+)", dep)
    return dep if not m or os.path.isdir(os.path.join(folder, m.group(1))) else None


def keep_script(folder, s):
    path = s.split(":", 1)[1] if ":" in s else s
    return s if path.startswith(".pio/") or os.path.isfile(os.path.join(folder, path)) else None


def build(folder, newest=False):
    if not os.path.isfile(os.path.join(folder, ".rsim-name")):  # written by the launcher's download, as pin_simlib.py
        return "adapter: not a downloaded firmware, left as is"
    ini = open(os.path.join(folder, "platformio.ini"), encoding="utf-8").read()
    if not re.search(r"^extra_configs\s*=.*platformio\.local\.ini", ini, re.M):
        return "adapter: platformio.ini does not load platformio.local.ini, left as is"
    if re.search(r"^\[env:[^\]]*simulator[^\]]*\]", ini, re.M):
        return "adapter: this firmware has its own simulator setup, left as is"
    local = os.path.join(folder, "platformio.local.ini")
    old = open(local, encoding="utf-8").read() if os.path.isfile(local) else ""
    if old and MARK not in old:
        return "adapter: platformio.local.ini was not written by the reader simulator, left as is"
    sha = lib_commit(folder, newest)
    sample = next((s for s in (raw(sha, n) for n in SAMPLES) if s), None)
    if not sample:
        return f"adapter: no sample config in {LIB}@{sha[:8]}"
    cp = configparser.ConfigParser(interpolation=None, comment_prefixes=(";", "#"), strict=False)
    cp.optionxform = str
    cp.read_string(sample)
    old_x3 = "FREEINK_DEVICE_" not in ini and any(
        "deviceIsX3" in open(os.path.join(r, f), encoding="utf-8", errors="replace").read()
        for r, _, fs in os.walk(os.path.join(folder, "src")) for f in fs if f.endswith((".h", ".cpp")))
    has_version = re.search(r"^\[crosspoint\]\n(?:(?!^\[).*\n)*?version\s*=", ini, re.M)
    out, made = [HEAD.rstrip("\n"), f"; library: {LIB}@{sha}"], []
    for section, name, need in ENVS:
        if not cp.has_section("env:" + section) or (need and not re.search(need, ini) and not (old_x3 and name == "simulator_x3")):
            continue
        out.append(f"\n[env:{name}]")
        for key, value in cp.items("env:" + section):
            vals = lines(value)
            if key == "lib_deps":
                vals = [d for d in (keep_dep(folder, v, sha) for v in vals) if d]
                # forks add SDK libraries the sample does not list (XPoint: FreeInkBook); hardware ones stay
                # out (the simulator library stands in for them), so do network ones (radio, TLS)
                skip = set(re.split(r"[\s,]+", cp.get("env:" + section, "lib_ignore", fallback=""))) | {"ContentProtection"}  # the library brings its own stand-in
                skip |= {v.split("=")[0] for v in vals}
                for lib, path in sorted(set(re.findall(
                        r"^\s*(\w+)=symlink://(freeink-sdk/libs/(?:book|font|ui|assets)/\w+)\s*$", ini, re.M))):
                    if lib not in skip and os.path.isdir(os.path.join(folder, path)):
                        vals.append(f"{lib}=symlink://{path}")
                        skip.add(lib)
            elif key == "extra_scripts":
                vals = [s for s in (keep_script(folder, v) for v in vals) if s]
            elif key == "build_flags" and has_version:  # the home screen shows the firmware's own version
                vals = [r'-DCROSSPOINT_VERSION=\"${crosspoint.version}\"' if v.startswith("-DCROSSPOINT_VERSION=") else v
                        for v in vals]
            if key == "build_flags" and section == "simulator":
                # the first samples (before 2026-04-23) were for macOS with Homebrew's SDL2
                vals = ["!sdl2-config --cflags --libs" if v == "-lSDL2" else v for v in vals
                        if not re.match(r"-arch\b|-[IL]/opt/homebrew", v)] + WIN_FLAGS
            out.append(f"{key} =" + "".join("\n  " + v for v in vals) if len(vals) != 1 or key in (
                "lib_deps", "build_flags", "extra_scripts", "build_src_filter") else f"{key} = {vals[0]}")
        made.append(name)
    text = "\n".join(out) + "\n"
    if text == old:
        return f"adapter: already: {', '.join(made)} with {LIB}@{sha[:8]}"
    open(local, "w", encoding="utf-8", newline="\n").write(text)
    return f"adapter: wrote {', '.join(made)} with {LIB}@{sha[:8]}"


if __name__ == "__main__":
    folder = os.path.abspath(sys.argv[1])
    # build.sh leaves platformio.local.ini.dated after the dated library failed once: newest from then on
    print(build(folder, "--newest" in sys.argv[2:] or os.path.isfile(os.path.join(folder, "platformio.local.ini.dated"))))
